"""Embed intrinsics.py into spy-intrinsics.h, modules/*.py into spy-std-modules.h,
and each stdlib/NAME.py into stdlib/NAME-source.h.

The engine runs intrinsics.py lazily; the standard layer (spy-std.c) registers
the modules; a C module of the standard library (stdlib/NAME.c) runs its
Python source when it is imported. Ordinary builds use the checked-in headers and do not need Python.
Full-line comments are dropped.
"""

import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def array(name, source):
    lines = []
    for line in source.splitlines():
        if line.lstrip().startswith("#"):
            continue
        escaped = line.replace('\\', '\\\\').replace('"', '\\"')
        lines.append(f'    "{escaped}\\n",')
    return f'static const char *const {name}[] = {{\n' + '\n'.join(lines) + '\n};\n'


def render(source):
    return ('/* Generated by tools/build_intrinsics.py from intrinsics.py. Do not edit. */\n'
            + array('intrinsics_source', source))


def render_modules(modules):
    names = [name for name, _ in modules]
    text = '/* Generated by tools/build_intrinsics.py from modules/. Do not edit. */\n'
    for name, module in modules:
        text += array(f"module_{name.replace('.', '_')}", module)
    text += ('static const struct { const char *name; const char *const *lines; size_t count; int package; } std_modules[] = {\n')
    for name in names:
        ident = f"module_{name.replace('.', '_')}"
        package = int(any(other.startswith(name + '.') for other in names))
        text += f'    {{"{name}", {ident}, sizeof({ident}) / sizeof(*{ident}), {package}}},\n'
    return text + '};\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='fail if the header is stale')
    args = parser.parse_args()
    modules = [(path.stem, path.read_text(encoding='utf-8')) for path in sorted((ROOT / 'modules').glob('*.py'))]
    outputs = {ROOT / 'spy-intrinsics.h': render((ROOT / 'intrinsics.py').read_text(encoding='utf-8')),
               ROOT / 'spy-std-modules.h': render_modules(modules)}
    for path in sorted((ROOT / 'stdlib').glob('*.py')):
        outputs[path.with_name(path.stem + '-source.h')] = (
            f'/* Generated by tools/build_intrinsics.py from stdlib/{path.name}. Do not edit. */\n'
            + array('source', path.read_text(encoding='utf-8')))
    for header, text in outputs.items():
        if args.check:
            if not header.exists() or header.read_text(encoding='utf-8') != text:
                raise SystemExit(f'{header.name} is stale; run make intrinsics')
        else:
            header.write_text(text, encoding='utf-8')


if __name__ == '__main__':
    main()
