"""Embed intrinsics.py into spy-intrinsics.h as C source lines.

The engine runs this source lazily; ordinary builds use the checked-in header
and do not need Python. Full-line comments are dropped.
"""

import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def render(source):
    lines = []
    for line in source.splitlines():
        if line.lstrip().startswith("#"):
            continue
        escaped = line.replace('\\', '\\\\').replace('"', '\\"')
        lines.append(f'    "{escaped}\\n",')
    return ('/* Generated by tools/build_intrinsics.py from intrinsics.py. Do not edit. */\n'
            'static const char *const intrinsics_source[] = {\n' + '\n'.join(lines) + '\n};\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='fail if the header is stale')
    args = parser.parse_args()
    text = render((ROOT / 'intrinsics.py').read_text(encoding='utf-8'))
    header = ROOT / 'spy-intrinsics.h'
    if args.check:
        if header.read_text(encoding='utf-8') != text:
            raise SystemExit('spy-intrinsics.h is stale; run make intrinsics')
        return
    header.write_text(text, encoding='utf-8')


if __name__ == '__main__':
    main()
