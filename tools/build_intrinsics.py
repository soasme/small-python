"""Embed intrinsics.py and the built-in modules/*.py into spy-intrinsics.h.

The engine runs these sources lazily; ordinary builds use the checked-in header
and do not need Python. Full-line comments are dropped.
"""

import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def array(name, source):
    lines = []
    for line in source.splitlines():
        if line.lstrip().startswith("#"):
            continue
        escaped = line.replace('\\', '\\\\').replace('"', '\\"')
        lines.append(f'    "{escaped}\\n",')
    return f'static const char *const {name}[] = {{\n' + '\n'.join(lines) + '\n};\n'


def render(source, modules=()):
    text = ('/* Generated by tools/build_intrinsics.py from intrinsics.py and modules/. Do not edit. */\n'
            + array('intrinsics_source', source))
    for name, module in modules:
        text += array(f"module_{name.replace('.', '_')}", module)
    return text


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='fail if the header is stale')
    args = parser.parse_args()
    modules = [(path.stem, path.read_text(encoding='utf-8')) for path in sorted((ROOT / 'modules').glob('*.py'))]
    text = render((ROOT / 'intrinsics.py').read_text(encoding='utf-8'), modules)
    header = ROOT / 'spy-intrinsics.h'
    if args.check:
        if header.read_text(encoding='utf-8') != text:
            raise SystemExit('spy-intrinsics.h is stale; run make intrinsics')
        return
    header.write_text(text, encoding='utf-8')


if __name__ == '__main__':
    main()
