# spec: PLS-315 23.5, 22.1, 22.3, 22.4
# description: The format specification mini-language for str, int, float, complex and other objects.
from harness import *

# Alignment and padding.
assert_eq(format("ab", "<5"), "ab   ")
assert_eq(format("ab", ">5"), "   ab")
assert_eq(format("ab", "^5"), " ab  ")
assert_eq(format("ab", "*^6"), "**ab**")
assert_eq(format(42, "5"), "   42")
assert_eq(format("s", "5"), "s    ")
assert_eq(format(-42, "=6"), "-   42")
assert_eq(format(-42, "06"), "-00042")
assert_eq(format("ab", "05"), "ab000")
assert_eq(format(255, "#010x"), "0x000000ff")
assert_eq(format(1234, "010,"), "00,001,234")
assert_eq(format(1234, "^010,"), "001,234000")
assert_eq(format(5, "^05"), "00500")
assert_eq(format("a", "^05"), "00a00")
assert_eq(format(5, "x^05"), "xx5xx")
assert_eq(format(-1, "x<4"), "-1xx")
# Strings.
assert_eq(format("abcdef", ".3"), "abc")
assert_eq(format("abcdef", "5.2s"), "ab   ")
def bad(value, spec):
    return str(assert_raises(ValueError, format, value, spec))
assert_eq(bad("a", "+"), "Sign not allowed in string format specifier")
assert_eq(bad("a", "=5"), "'=' alignment not allowed in string format specifier")
assert_eq(bad("a", "#"), "Alternate form (#) not allowed in string format specifier")
assert_eq(bad("a", "z"), "Negative zero coercion (z) not allowed in string format specifier")
assert_eq(bad("a", ","), "Cannot specify ',' with 's'.")
assert_eq(bad("a", "d"), "Unknown format code 'd' for object of type 'str'")
assert_eq(bad("a", "ss"), "Invalid format specifier 'ss' for object of type 'str'")
assert_eq(bad(1, ",_"), "Cannot specify both ',' and '_'.")
assert_eq(bad(1, "9999999999999999999999"), "Too many decimal digits in format string")
# Integers.
assert_eq([format(10, t) for t in "bodxXn"], ["1010", "12", "10", "a", "A", "10"])
assert_eq([format(10, "#" + t) for t in "boxX"], ["0b1010", "0o12", "0xa", "0XA"])
assert_eq([format(5, s) for s in ("+", "-", " ")], ["+5", "5", " 5"])
assert_eq([format(-5, s) for s in ("+", "-", " ")], ["-5", "-5", "-5"])
assert_eq(format(1234567, ","), "1,234,567")
assert_eq(format(1234567, "_"), "1_234_567")
assert_eq(format(0xABCDEF, "_x"), "ab_cdef")
assert_eq(format(255, "_b"), "1111_1111")
assert_eq(format(97, "c"), "a")
assert_eq(format(3, "e"), "3.000000e+00")
assert_eq(format(3, "%"), "300.000000%")
assert_eq(bad(1, ".2"), "Precision not allowed in integer format specifier")
assert_eq(bad(1, "z"), "Negative zero coercion (z) not allowed in integer format specifier")
assert_eq(bad(1, ",x"), "Cannot specify ',' with 'x'.")
assert_eq(bad(1, "+c"), "Sign not allowed with integer format specifier 'c'")
assert_eq(bad(1, "#c"), "Alternate form (#) not allowed with integer format specifier 'c'")
assert_eq(bad(1, "s"), "Unknown format code 's' for object of type 'int'")
e = assert_raises(OverflowError, format, 0x110000, "c")
assert_eq(str(e), "%c arg not in range(0x110000)")
# Floats.
assert_eq(format(1234.5678, "e"), "1.234568e+03")
assert_eq(format(1234.5678, "E"), "1.234568E+03")
assert_eq(format(1.5, ".0e"), "2e+00")
assert_eq(format(1.5, "#.0e"), "2.e+00")
assert_eq(format(2.5, ".0f"), "2")
assert_eq(format(0.125, ".2f"), "0.12")
assert_eq(format(1.0, "#.0f"), "1.")
assert_eq(format(1e-5, "g"), "1e-05")
assert_eq(format(123456789.0, "g"), "1.23457e+08")
assert_eq(format(0.0001, "g"), "0.0001")
assert_eq(format(1.5, "g"), "1.5")
assert_eq(format(1.5, "#g"), "1.50000")
assert_eq(format(100.0, ".2g"), "1e+02")
assert_eq(format(0.25, "%"), "25.000000%")
assert_eq(format(1.5, ""), "1.5")
assert_eq(format(1e16, ""), "1e+16")
assert_eq(format(1.0, ".3"), "1.0")
assert_eq(format(123.0, ".2"), "1.2e+02")
assert_eq(format(float("inf"), "f"), "inf")
assert_eq(format(float("-inf"), "F"), "-INF")
assert_eq(format(float("nan"), "E"), "NAN")
assert_eq(format(-0.0001, ".1f"), "-0.0")
assert_eq(format(-0.0001, "z.1f"), "0.0")
assert_eq(format(1234567.125, ",.2f"), "1,234,567.12")
assert_eq(format(1.23456789, ".6_f"), "1.234_568")
assert_eq(format(1.5, "n"), "1.5")
assert_eq(bad(1.5, "d"), "Unknown format code 'd' for object of type 'float'")
assert_eq(bad(1.5, "x"), "Unknown format code 'x' for object of type 'float'")
# Complex.
assert_eq(format(1 + 2j, ""), "(1+2j)")
assert_eq(format(1 + 2j, ".2f"), "1.00+2.00j")
assert_eq(format(1 - 2j, "+.1f"), "+1.0-2.0j")
assert_eq(format(2j, ".1"), "2j")
assert_eq(format(1 + 2j, "10"), "    (1+2j)")
assert_eq(format(1.5 + 2j, "<12.3"), "(1.5+2j)    ")
assert_eq(bad(1j, "=10"), "'=' alignment flag is not allowed in complex format specifier")
assert_eq(bad(1j, "010"), "Zero padding is not allowed in complex format specifier")
# Other objects and bool.
class Plain: pass
assert_eq(format(Plain(), "").startswith("<"), True)
e = assert_raises(TypeError, format, Plain(), "x")
assert_eq(str(e), "unsupported format string passed to Plain.__format__")
assert_eq(format(True, ""), "True")
assert_eq(format(True, "d"), "1")
assert_eq(format(True, ">3"), "  1")
