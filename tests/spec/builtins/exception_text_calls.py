# spec: PLS-315 21.1.6, 21.3.3, 7.3
# description: str() and repr() of an exception whose text is that of its
# argument, or of its arguments' tuple, call the argument's Python
# __str__ or __repr__ (an item's for the tuple) in order, KeyError's str
# its repr; the method's exception propagates and a __repr__ that returns
# no str raises TypeError; OSError without an errno and ImportError without
# a str message format their arguments alike, and an ImportError given a
# name or path, even None, shows it.
from harness import *

log = []
class R:
    def __init__(self, n, bad=None):
        self.n, self.bad = n, bad
    def __repr__(self):
        for _ in (): pass
        log.append(("repr", self.n))
        if self.bad == "raise": raise ValueError("r")
        if self.bad == "int": return 5
        return f"R{self.n}"
    def __str__(self):
        for _ in (): pass
        log.append(("str", self.n))
        if self.bad == "raise": raise ValueError("s")
        return f"S{self.n}"
