# spec: PLS-315 7.6.2, 22.3.2
# description: Mixed int/float/complex operands are converted to the wider type.
from harness import *

assert_same(1 + 2.0, 3.0)
assert_same(2.0 * 3, 6.0)
assert_same(1 + 2j, complex(1, 2))
assert_same(1.5 + 1j, complex(1.5, 1))
assert_same(True + 1, 2)
assert_same(True + 1.0, 2.0)
assert_same(True + True, 2)
assert_same(False * 3j, 0j)
assert_same(7 / 2, 3.5)
assert_same(8 / 2, 4.0)
assert_same(2 ** -1, 0.5)
assert_same(2 ** 3, 8)
assert_same((-8) ** (1 / 3), complex(1.0000000000000002, 1.7320508075688772))
assert_same(10 % 3.0, 1.0)
assert_same(divmod(7, 2), (3, 1))
assert_same(divmod(7.0, 2), (3.0, 1.0))
# bool is a subclass of int; arithmetic on bools gives ints.
assert_same(-True, -1)
assert_same(~False, -1)
assert_same(True & False, False)
assert_same(True | 2, 3)
# A type without an operator declines it; the TypeError names the operator
# (op= for an augmented assignment) and both operand types.
def message(source, namespace=None):
    e = assert_raises(TypeError, run, source, namespace)
    return str(e)
assert_eq(message("1j // 2"), "unsupported operand type(s) for //: 'complex' and 'int'")
assert_eq(message("1 << 1.0"), "unsupported operand type(s) for <<: 'int' and 'float'")
assert_eq(message("True @ False"), "unsupported operand type(s) for @: 'bool' and 'bool'")
assert_eq(message("divmod(1j, 1)"), "unsupported operand type(s) for divmod(): 'complex' and 'int'")
assert_eq(message("x = 1\nx **= 'a'"), "unsupported operand type(s) for **=: 'int' and 'str'")
assert_eq(message("x = None\nx *= None"), "unsupported operand type(s) for *=: 'NoneType' and 'NoneType'")
assert_eq(message("None * 2"), "unsupported operand type(s) for *: 'NoneType' and 'int'")
assert_eq(message("pow(None, 1, 2)"), "unsupported operand type(s) for ** or pow(): 'NoneType', 'int', 'int'")
assert_eq(message("pow(1, 2.0, 3)"), "pow() 3rd argument not allowed unless all arguments are integers")
e = assert_raises(ValueError, pow, 1j, 2, 3)
assert_eq(str(e), "complex modulo")
e = assert_raises(ZeroDivisionError, lambda: 1j / 0)
assert_eq(str(e), "division by zero")
e = assert_raises(OverflowError, lambda: (1 + 1j) ** 1000000)
assert_eq(str(e), "complex exponentiation")
