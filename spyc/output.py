from .resolve import MODULE, PACKAGE


def c_bytes(data):
    """A C array's initializer: each byte, 24 to a line, then the 0."""
    out = []
    for i, byte in enumerate(data):
        out.append(f"{byte},\n" if i % 24 == 23 else f"{byte},")
    out.append("0};\n")
    return "".join(out)


def c_string(text):
    """A C string literal, escaping all but plain ASCII."""
    out = ['"']
    for byte in text.encode("utf-8"):
        ch = chr(byte)
        out.append(ch if byte < 128 and (ch.isalnum() or ch in "_.") else f"\\{byte:03o}")
    out.append('"')
    return "".join(out)


def json_string(text):
    out = ['"']
    for ch in text:
        out.append("\\" + ch if ch in '"\\' else f"\\u{ord(ch):04x}" if ord(ch) < 32 else ch)
    out.append('"')
    return "".join(out)


def make_path(text):
    """A path in a make rule."""
    return "".join("\\" + ch if ch in " #" else "$$" if ch == "$" else ch for ch in text)


def c_name(entry, module):
    """A C identifier for an entry: spy_ and its name, as spyc -c names it."""
    base = entry if module else entry.rpartition("/")[2]
    if not module:
        base = base.partition(".")[0]
    return "spy_" + "".join(chr(b) if b < 128 and chr(b).isalnum() else "_" for b in base.encode("utf-8"))


LOADER = """/* A SPYModuleLoader over the bundled modules: the source the engine
 * asks for by name, as bytes, or NULL. */
{static}SPYValue *{name}(SPYContext *c, void *data, const char *name) {{
    size_t low = 0, high = sizeof modules / sizeof *modules - 1;
    (void)data;
    while (low < high) {{
        size_t middle = low + (high - low) / 2;
        int order = strcmp(name, modules[middle].name);
        if (!order) return spy_bytes(c, modules[middle].source, modules[middle].size - 1);
        if (order < 0) high = middle; else low = middle + 1;
    }}
    return NULL;
}}
"""

MAIN = r"""static int output(SPYContext *c, void *p, const char *s, size_t n) {
    (void)c;
    return fwrite(s, 1, n, (FILE *)p) == n ? 0 : -1;
}
static int flush_output(SPYContext *c, void *p) { (void)c; return fflush((FILE *)p); }
static int global(SPYContext *c, const char *name, const char *text) {
    SPYValue *value = spy_string(c, text, strlen(text));
    int status = !value || spy_set_global(c, name, value);
    spy_release(value);
    return status;
}
/* The process status for the pending error, as python's: SystemExit's
 * code (None 0, an int its low byte, 255 when it does not fit, otherwise
 * printed and 1); any other error is reported, and 1. */
static int exit_status(SPYContext *c) {
    SPYValue *error = strcmp(spy_error_type(c), "SystemExit") ? NULL : spy_error_value(c);
    SPYValue *code = error ? spy_get_attr(c, error, "code") : NULL;
    spy_release(error);
    if (!code) {
        fprintf(stderr, "%s:%zu: %s: %s\n",
            spy_error_filename(c), spy_error_line(c), spy_error_type(c), spy_error_display(c));
        return 1;
    }
    spy_clear_error(c);
    int64_t status = 1;
    if (spy_type(code) == SPY_NONE) status = 0;
    else if (!spy_as_int(c, code, &status)) status &= 0xff;
    else if (!strcmp(spy_error_type(c), "OverflowError")) status = 255;
    else {
        SPYValue *text = (spy_clear_error(c), spy_str(c, code));
        const char *s = text ? spy_as_string(c, text, NULL) : NULL;
        if (s) fprintf(stderr, "%s\n", s);
        spy_release(text);
    }
    spy_release(code);
    return (int)status;
}
int main(int argc, char **argv) {
    SPYContext *c = spy_context_new();
    if (!c) return 1;
    /* As the spy command: open reaches the working directory, if any. */
    if (spy_mount(c, ".", NULL, 0)) spy_clear_error(c);
"""


def generate(entries, table, inputs, loader, bare, registered, natives, optimize):
    """The C file: the sources, the module table and its loader, and
    unless BARE the program's main for the first entry."""
    out = []
    if bare:
        out.append(f"/* Generated by spyc -c. A host installs {loader} with spy_set_module_loader\n"
                   " * and runs an entry with spy_exec. */\n#include \"spy.h\"\n#include <stdlib.h>\n#include <string.h>\n")
    else:
        libraries = "libspy.a, libspy-std.a," if registered else "libspy.a"
        standard = '#include "spy-std.h"\n' if registered else ""
        out.append(f"/* Generated by spyc. Link with {libraries} and the C math library. */\n#include \"spy.h\"\n{standard}"
                   "#include <stdio.h>\n#include <stdlib.h>\n#include <string.h>\n")
        for name in natives:
            out.append(f"int spy_init_{name}(SPYContext *, SPYValue *);\n")
    for i, m in enumerate(inputs):
        if i < len(entries):
            out.append(f"{'' if bare else 'static '}const char {m.array}[] = {{\n")
        else:
            out.append(f"static const char {m.array}[] = {{ /* {m.path} */\n")
        out.append(c_bytes(m.source))
    out.append("static const struct { const char *name, *source; size_t size; } modules[] = {\n")
    for m in table:
        out.append("    {" + c_string(m.name))
        if m.kind != MODULE:
            out.append(' ".__init__"' if m.kind == PACKAGE else ' ".__namespace__"')
        out.append(f", {m.array}, sizeof {m.array}}},\n")
    out.append("    {NULL, NULL, 0}\n};\n")
    out.append(LOADER.format(static="" if bare else "static ", name=loader if bare else "load"))
    if not bare:
        e = entries[0]
        out.append(MAIN)
        for name in registered:
            out.append(f"    if (spy_std_init_module(c, \"{name}\")) return 1;\n")
        for name in natives:
            out.append(f"    if (spy_new_module(c, \"{name}\", spy_init_{name})) return 1;\n")
        if optimize:
            out.append(f"    spy_set_optimize(c, {optimize});\n")
        out.append("    spy_set_output(c, output, flush_output, stdout);\n"
                   "    spy_set_error_output(c, output, flush_output, stderr);\n"
                   "    spy_set_module_loader(c, load, NULL);\n"
                   "    int status = spy_set_argv(c, (size_t)argc, (const char *const *)argv, (size_t)argc, (const char *const *)argv) ||\n"
                   f"        global(c, \"__file__\", {c_string(e.file)});\n")
        if e.package is not None:
            # As python -m: the package is set, and imported first.
            out.append(f"    if (!status) status = global(c, \"__package__\", {c_string(e.package)});\n")
            if e.package:
                imports = c_string("__import__('" + e.package + "')")
                out.append(f"    if (!status) {{\n        spy_release(spy_eval(c, {imports}, \"<spyc>\"));\n"
                           "        status = spy_error_type(c)[0] != 0;\n    }\n")
        out.append(f"    if (!status) status = spy_exec(c, source, {c_string(e.file)});\n"
                   "    if (status) status = exit_status(c);\n"
                   "    spy_context_free(c);\n"
                   "    return status;\n}\n")
    return "".join(out).encode("utf-8")


def metafile(inputs, output, size, entry):
    out = ['{\n  "inputs": {']
    for i, m in enumerate(inputs):
        out.append(("," if i else "") + "\n    " + json_string(m.path) + f": {{\"bytes\": {m.bytes}, \"imports\": [")
        shown = 0
        for path, original, kind, flag in m.imports:
            if kind == "maybe":
                continue
            out.append(("," if shown else "") + "\n      {\"path\": " + json_string(path) + f", \"kind\": \"{kind}\", \"original\": " +
                       json_string(original) + (", \"external\": true" if flag == 1 else ", \"missing\": true" if flag == 2 else "") + "}")
            shown += 1
        out.append("]}")
    out.append("\n  },\n  \"outputs\": {\n    " + json_string(output) + f": {{\"bytes\": {size}, \"entryPoint\": " + json_string(entry) +
               ", \"inputs\": {")
    for i, m in enumerate(inputs):
        out.append(("," if i else "") + "\n      " + json_string(m.path) + f": {{\"bytesInOutput\": {len(m.source)}}}")
    out.append("}}\n  }\n}\n")
    return "".join(out).encode("utf-8")


def rule(output, inputs, natives):
    return output + ":" + "".join(" " + make_path(m.path) for m in inputs) + \
        "".join(" " + make_path(path) for path in natives) + "\n"
