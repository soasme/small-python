"""Write fuzz/fuzz.dict, the libFuzzer dictionary, as QuickJS's generate_dict.js.

Keywords and operators are listed here; builtin names and the attributes of
builtin types come from ./spy itself, so the dictionary follows the engine.
Run it after `make spy`: python3 fuzz/generate_dict.py
"""

import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

KEYWORDS = """False None True and as assert async await break class continue def
del elif else except finally for from global if import in is lambda nonlocal
not or pass raise return try while with yield match case type _""".split()

TOKENS = """+ - * ** / // % @ << >> & | ^ ~ := < > <= >= == != ( ) [ ] { } , : ! .
; = -> += -= *= /= //= %= @= &= |= ^= >>= <<= **= ... \\ # 0x 0o 0b 0j 1e9 1_0
' " ''' \"\"\" f' rb' t' u' br' { } {!r} {:>10} \\n \\t \\x00 \\u00e9 \\N{BULLET}
# -*- coding: latin-1 -*-""".split("\n")

ENUMERATE = r"""
names = set(dir(__builtins__))
for value in (object, type, int, float, complex, bool, str, bytes, bytearray,
              list, tuple, dict, set, frozenset, range, slice, memoryview,
              BaseException, property, staticmethod, classmethod, super):
    names.update(dir(value))
for name in sorted(names):
    print(name)
"""


def entry(token):
    escaped = "".join(c if c.isprintable() and c not in '"\\' else f"\\x{ord(c):02x}"
                      for c in token)
    return f'"{escaped}"'


def main():
    spy = ROOT / "spy"
    names = subprocess.run([str(spy), "-c", ENUMERATE], check=True,
                           capture_output=True, text=True).stdout.split()
    tokens = KEYWORDS + [t for line in TOKENS for t in line.split()] + TOKENS[-1:]
    tokens += ["\n", "\n    ", "    "] + names
    seen = []
    for token in tokens:
        if token not in seen:
            seen.append(token)
    out = ROOT / "fuzz" / "fuzz.dict"
    out.write_text("# Generated by fuzz/generate_dict.py. Do not edit.\n"
                   + "".join(entry(t) + "\n" for t in seen))
    print(f"{out.relative_to(ROOT)}: {len(seen)} entries", file=sys.stderr)


if __name__ == "__main__":
    main()
