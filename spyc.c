#include "host.h"
#include <string.h>

/* Generate a C translation unit. A normal C compiler then links the runtime;
 * no shell, compiler executable, or platform process API is hidden here. */
int main(int argc, char **argv) {
    if (argc != 4 || strcmp(argv[1], "-o") || !strcmp(argv[2], argv[3])) {
        fputs("usage: spyc -o program.c input.py\n", stderr); return 2;
    }
    FILE *input = fopen(argv[3], "rb");
    if (!input) { perror(argv[3]); return 1; }
    char *source = host_read(input);
    fclose(input);
    if (!source) { fputs("cannot read source\n", stderr); return 1; }
    FILE *out = fopen(argv[2], "w");
    if (!out) { perror(argv[2]); free(source); return 1; }
    fputs("/* Generated by spyc. Link with spy.c and the C math library. */\n"
          "#include \"spy.h\"\n#include <stdio.h>\n"
          "static const char source[] = {\n", out);
    for (size_t i = 0; source[i]; i++) {
        fprintf(out, "%u,", (unsigned char)source[i]);
        if (i % 24 == 23) fputc('\n', out);
    }
    fputs("0};\n"
          "static int output(void *p, const char *s, size_t n) {\n"
          "    return fwrite(s, 1, n, (FILE *)p) == n ? 0 : -1;\n}\n"
          "int main(void) {\n"
          "    SPYContext *c = spy_context_new();\n"
          "    if (!c) return 1;\n"
          "    spy_set_output(c, output, stdout);\n"
          "    int status = spy_exec(c, source, \"<embedded>\");\n"
          "    if (status) fprintf(stderr, \"%s:%zu: %s: %s\\n\",\n"
          "        spy_error_filename(c), spy_error_line(c), spy_error_type(c), spy_error_message(c));\n"
          "    spy_context_free(c);\n"
          "    return status ? 1 : 0;\n}\n", out);
    int failed = ferror(out);
    if (fclose(out)) failed = 1;
    free(source);
    if (failed) { fputs("cannot write generated C\n", stderr); return 1; }
    return 0;
}
